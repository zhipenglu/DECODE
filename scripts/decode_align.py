#!/usr/bin/env python3
"""
DECODE Stage 1: Transition-Invariant 2-Base Alignment & 4-Base Restoration
===========================================================================

Overview
--------
Chemical deamination probing introduces dense bidirectional purine transitions
(A <-> G) and pyrimidine transitions (C -> T/U) that cause standard 4-base and
bisulfite aligners to fail once mutation loads exceed ~10-15%. This script
implements Stage 1 of the DECODE pipeline by decoupling coordinate discovery
from mutation quantification:

1. 2-Base Alphabet Projection
   - Sense reads (5' -> 3' RNA orientation) are projected onto the degenerate
     purine/pyrimidine alphabet: {A, G} -> G and {C, T, U} -> T.
   - In paired-end libraries (e.g., standard dUTP/fr-secondstrand protocols),
     the antisense mate (R2) is projected onto the complementary {C, A}
     alphabet ({A, G} -> C; {C, T, U} -> A) so STAR evaluates proper paired-end
     insert sizes and splice junctions against _fwd and _rev contigs.

2. Lossless 4-Base Read Archiving
   - Before alignment, original read headers and 4-base sequences are written
     to a binary-indexed, memory-mapped sidecar store (orig_reads.dat / .idx)
     and replaced with compact integer IDs (R0, R1, ...).
   - This avoids the 254-character SAM QNAME limit, enabling lossless 4-base
     restoration for both short Illumina reads and multi-kilobase long reads.

3. Gap-Aware Alignment & 4-Base BAM Restoration
   - Projected FASTQs are aligned with STAR against the dual-strand 2-base
     index generated by `decode_index.py` (retaining up to `--max-multimap`
     candidate loci per read for downstream Bayesian paralog resolution).
   - Every alignment record is restored to its true 4-base sequence, standard
     4-base MD:Z and NM:i tags are recomputed against `reference_4base_dual.fa`,
     and custom provenance tags are attached:
       * Y2:i  2-base (G/T) edit distance reported by STAR
       * YS:Z  Decoded genomic strand ('+' for _fwd contigs, '-' for _rev)

Usage Examples
--------------
Single-end or long-read FASTQ:
    python scripts/decode_align.py \
        --index decode_idx \
        --r1 sample.fastq.gz \
        --threads 8 \
        --out sample.restored.bam

Paired-end FASTQ (standard Illumina directional):
    python scripts/decode_align.py \
        --index decode_idx \
        --r1 sample_R1.fastq.gz \
        --r2 sample_R2.fastq.gz \
        --orientation fr-secondstrand \
        --threads 16 \
        --out sample.restored.bam
"""

import argparse
import gzip
import mmap
import os
import shutil
import struct
import subprocess
import sys
import tempfile

import pysam

# Lookup tables for reverse-complementation and 2-base projections
COMP_TAB = str.maketrans("ACGTUacgtuNn", "TGCAAtgcaaNn")
GT_TAB = str.maketrans("ACGTUacgtuNn", "GTGTTgtgttNn")  # {A,G}->G; {C,T,U}->T
CA_TAB = str.maketrans("ACGTUacgtuNn", "CACAAcacaaNn")  # {A,G}->C; {C,T,U}->A


def open_text(path, mode="rt"):
    """Open a plain-text or gzip-compressed file transparently."""
    return gzip.open(path, mode) if path.endswith(".gz") else open(path, mode)


def revcomp(seq):
    """Return the 5'->3' reverse complement of a 4-base DNA/RNA sequence."""
    return seq.translate(COMP_TAB)[::-1]


def iter_fastq(path):
    """
    Stream records from a FASTQ file.

    Yields:
        tuple[str, str, str]: (clean_read_name, sequence, phred_qualities)
    """
    with open_text(path) as fh:
        while True:
            hdr = fh.readline()
            if not hdr:
                break
            seq = fh.readline().rstrip("\r\n")
            fh.readline()  # Skip '+' separator line
            qual = fh.readline().rstrip("\r\n")
            qname = hdr[1:].strip().split()[0]
            yield qname, seq, qual


def prepare_projected_fastqs(r1_path, r2_path, orientation, tmp_dir):
    """
    Project FASTQ reads to 2-base space and archive original 4-base sequences.

    Each read (or read pair) is assigned a compact sequential ID (`R0`, `R1`,
    ...) in the temporary 2-base FASTQs while its original header and 4-base
    sequences are stored at a fixed byte offset in `orig_reads.dat` indexed by
    `orig_reads.idx` (little-endian uint64 offsets).

    Args:
        r1_path (str): Path to R1 FASTQ (.fq or .fq.gz).
        r2_path (str | None): Path to R2 FASTQ for paired-end data, or None.
        orientation (str): Library strandedness ('fr-secondstrand',
            'fr-firststrand', or 'same-strand').
        tmp_dir (str): Scratch directory for temporary FASTQs and read store.

    Returns:
        tuple: (proj_r1, proj_r2, dat_path, idx_path, n_reads)
    """
    proj_r1 = os.path.join(tmp_dir, "proj_R1.fq")
    proj_r2 = os.path.join(tmp_dir, "proj_R2.fq") if r2_path else None
    dat_path = os.path.join(tmp_dir, "orig_reads.dat")
    idx_path = os.path.join(tmp_dir, "orig_reads.idx")

    # Select sense (G/T) vs. antisense (C/A) projection table per mate
    tab1 = CA_TAB if (r2_path and orientation == "fr-firststrand") else GT_TAB
    tab2 = GT_TAB if orientation == "fr-firststrand" else CA_TAB

    n_reads = 0
    offset = 0
    with open(proj_r1, "w") as f1, open(dat_path, "wb") as fdat, open(
        idx_path, "wb"
    ) as fidx:
        if r2_path is None:
            for qname, seq1, qual1 in iter_fastq(r1_path):
                rid = f"R{n_reads}"
                f1.write(f"@{rid}\n{seq1.translate(GT_TAB)}\n+\n{qual1}\n")
                rec = f"{qname}\t{seq1}\t\n".encode("ascii")
                fidx.write(struct.pack("<Q", offset))
                fdat.write(rec)
                offset += len(rec)
                n_reads += 1
        else:
            with open(proj_r2, "w") as f2:
                it1, it2 = iter_fastq(r1_path), iter_fastq(r2_path)
                for (q1, s1, u1), (q2, s2, u2) in zip(it1, it2):
                    rid = f"R{n_reads}"
                    f1.write(f"@{rid}\n{s1.translate(tab1)}\n+\n{u1}\n")
                    f2.write(f"@{rid}\n{s2.translate(tab2)}\n+\n{u2}\n")
                    rec = f"{q1}\t{s1}\t{s2}\n".encode("ascii")
                    fidx.write(struct.pack("<Q", offset))
                    fdat.write(rec)
                    offset += len(rec)
                    n_reads += 1
                if next(it1, None) is not None or next(it2, None) is not None:
                    sys.exit("ERROR: R1 and R2 FASTQ read counts do not match.")

    return proj_r1, proj_r2, dat_path, idx_path, n_reads


def run_star_align(
    star_bin, star_dir, proj_r1, proj_r2, threads, max_multimap, extra_args,
    tmp_dir
):
    """
    Execute gap-aware STAR alignment in degenerate 2-base space.

    Relaxed match/score filters (`0.5` over read length) accommodate non-deam
    sequencing errors or structural indels while retaining candidate paralog
    loci (`--outFilterMultimapNmax`) for Stage 2 Bayesian scoring.

    Returns:
        str: Path to unsorted STAR output BAM.
    """
    if shutil.which(star_bin) is None and not os.path.isfile(star_bin):
        sys.exit(f"ERROR: STAR binary not found: {star_bin}")
    prefix = os.path.join(tmp_dir, "star_")
    reads = [proj_r1, proj_r2] if proj_r2 else [proj_r1]
    cmd = [
        star_bin,
        "--runMode", "alignReads",
        "--runThreadN", str(threads),
        "--genomeDir", star_dir,
        "--readFilesIn", *reads,
        "--outFileNamePrefix", prefix,
        "--outSAMtype", "BAM", "Unsorted",
        "--outSAMunmapped", "Within",
        "--outSAMattributes", "NH", "HI", "AS", "nM", "MD",
        "--outFilterMultimapNmax", str(max_multimap),
        "--winAnchorMultimapNmax", "100",
        "--seedSearchStartLmax", "30",
        "--outFilterScoreMinOverLread", "0.5",
        "--outFilterMatchNminOverLread", "0.5",
    ]
    if extra_args:
        cmd.extend(extra_args.split())
    print("Running:", " ".join(cmd))
    subprocess.run(cmd, check=True)
    return prefix + "Aligned.out.bam"


def compute_md_nm(query_seq, ref_subseq, cigartuples):
    """
    Recompute standard SAM MD:Z and NM:i tags in 4-base space.

    Walks the CIGAR operations across the restored 4-base query sequence and
    the corresponding 4-base reference slice so downstream pileup and mutation
    callers observe true A/C/G/T mismatches and indels.

    Args:
        query_seq (str): Uppercase restored alignment SEQ (SAM orientation).
        ref_subseq (str): Uppercase 4-base reference slice [start, end).
        cigartuples (list[tuple[int, int]]): Parsed pysam CIGAR tuples.

    Returns:
        tuple[str, int]: (md_string, edit_distance_nm)
    """
    q_pos = 0
    r_pos = 0
    nm = 0
    md_parts = []
    match_run = 0
    for op, length in cigartuples:
        if op in (0, 7, 8):  # M, =, X (alignment match/mismatch)
            for i in range(length):
                qb = query_seq[q_pos + i]
                rb = ref_subseq[r_pos + i]
                if qb == rb and qb != "N":
                    match_run += 1
                else:
                    md_parts.append(str(match_run))
                    md_parts.append(rb)
                    match_run = 0
                    nm += 1
            q_pos += length
            r_pos += length
        elif op == 1:  # I (insertion to reference)
            q_pos += length
            nm += length
        elif op == 2:  # D (deletion from reference)
            md_parts.append(str(match_run))
            md_parts.append("^" + ref_subseq[r_pos:r_pos + length])
            match_run = 0
            r_pos += length
            nm += length
        elif op == 3:  # N (spliced intron skip)
            r_pos += length
        elif op == 4:  # S (soft clip)
            q_pos += length
    md_parts.append(str(match_run))
    return "".join(md_parts), nm


def slice_hard_clips(seq, cigartuples):
    """Remove terminal hard-clipped bases so SEQ length matches CIGAR."""
    if not cigartuples:
        return seq
    left = cigartuples[0][1] if cigartuples[0][0] == 5 else 0
    right = cigartuples[-1][1] if cigartuples[-1][0] == 5 else 0
    return seq[left:len(seq) - right] if (left or right) else seq


def restore_four_base_bam(
    raw_bam, fa_4b_path, dat_path, idx_path, restored_unsorted
):
    """
    Restore 4-base sequences and recompute 4-base tags across all BAM records.

    For each alignment record, looks up the archived 4-base sequence in O(1)
    time via memory-mapped offsets, reverse-complements if mapped to the
    reverse strand of a contig, recomputes 4-base MD/NM tags, and records the
    2-base edit distance (Y2:i) and decoded genomic strand (YS:Z).
    """
    ref_fa = pysam.FastaFile(fa_4b_path)
    with open(idx_path, "rb") as fidx, open(dat_path, "rb") as fdat:
        idx_mm = mmap.mmap(fidx.fileno(), 0, access=mmap.ACCESS_READ)
        dat_mm = mmap.mmap(fdat.fileno(), 0, access=mmap.ACCESS_READ)
        with pysam.AlignmentFile(raw_bam, "rb") as bam_in, (
            pysam.AlignmentFile(restored_unsorted, "wb", template=bam_in)
        ) as bam_out:
            for aln in bam_in:
                read_idx = int(aln.query_name[1:])
                off = struct.unpack_from("<Q", idx_mm, read_idx * 8)[0]
                end = dat_mm.find(b"\n", off)
                qname, s1, s2 = dat_mm[off:end].decode("ascii").split("\t")
                orig_seq = s2 if aln.is_read2 else s1
                if aln.is_reverse:
                    orig_seq = revcomp(orig_seq)
                orig_seq = slice_hard_clips(orig_seq, aln.cigartuples)

                # Cache qualities before replacing query_sequence (which clears
                # query_qualities in pysam)
                quals = aln.query_qualities
                aln.query_name = qname
                aln.query_sequence = orig_seq
                aln.query_qualities = quals

                if not aln.is_unmapped and aln.cigartuples:
                    rname = aln.reference_name
                    rsub = ref_fa.fetch(
                        rname, aln.reference_start, aln.reference_end
                    ).upper()
                    if aln.has_tag("NM"):
                        aln.set_tag("Y2", aln.get_tag("NM"), value_type="i")
                    md_str, nm_val = compute_md_nm(
                        orig_seq.upper(), rsub, aln.cigartuples
                    )
                    aln.set_tag("MD", md_str, value_type="Z")
                    aln.set_tag("NM", nm_val, value_type="i")
                    strand = "-" if rname.endswith("_rev") else "+"
                    aln.set_tag("YS", strand, value_type="Z")

                bam_out.write(aln)
        dat_mm.close()
        idx_mm.close()
    ref_fa.close()


def parse_args():
    """Parse command-line arguments."""
    p = argparse.ArgumentParser(
        description="Align reads in 2-base G/T space and restore 4-base BAM."
    )
    p.add_argument("--index", required=True, help="Directory from decode_index")
    p.add_argument("--r1", required=True, help="Input R1 FASTQ (.fq/.fq.gz)")
    p.add_argument("--r2", default=None, help="Optional R2 FASTQ (.fq/.fq.gz)")
    p.add_argument(
        "--orientation",
        default="fr-secondstrand",
        choices=["fr-secondstrand", "fr-firststrand", "same-strand"],
        help="Paired-end library orientation (default: fr-secondstrand)",
    )
    p.add_argument("--out", required=True, help="Output sorted 4-base BAM")
    p.add_argument("--threads", type=int, default=8, help="Worker threads")
    p.add_argument(
        "--max-multimap", type=int, default=20,
        help="Max candidate loci per read for Bayesian calling (default: 20)"
    )
    p.add_argument("--star-bin", default="STAR", help="Path to STAR binary")
    p.add_argument("--extra-star-args", default="",
                   help="Additional quoted arguments forwarded to STAR")
    p.add_argument("--tmpdir", default=None, help="Optional temp directory")
    return p.parse_args()


def main():
    """Run end-to-end 2-base projection, STAR alignment, and 4-base restore."""
    args = parse_args()
    star_dir = os.path.join(args.index, "STAR_index")
    fa_4b = os.path.join(args.index, "reference_4base_dual.fa")
    for req in (star_dir, fa_4b):
        if not os.path.exists(req):
            sys.exit(f"ERROR: Missing expected index artifact: {req}")

    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    with tempfile.TemporaryDirectory(dir=args.tmpdir) as tmp:
        proj_r1, proj_r2, dat_path, idx_path, n_reads = (
            prepare_projected_fastqs(
                args.r1, args.r2, args.orientation, tmp
            )
        )
        print(f"Projected {n_reads} reads/pairs into 2-base space.")
        raw_bam = run_star_align(
            args.star_bin, star_dir, proj_r1, proj_r2, args.threads,
            args.max_multimap, args.extra_star_args, tmp
        )
        restored_unsorted = os.path.join(tmp, "restored.unsorted.bam")
        restore_four_base_bam(
            raw_bam, fa_4b, dat_path, idx_path, restored_unsorted
        )
        pysam.sort("-@", str(args.threads), "-o", args.out, restored_unsorted)
        pysam.index(args.out)
    print(f"Saved sorted, indexed 4-base BAM -> {args.out}")


if __name__ == "__main__":
    main()
